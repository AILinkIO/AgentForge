    /**
     * 用户自己附东西时接在消息后面的那一行（主会话）。⚠️ 措辞是**事实**不是祈使（"直接看它"）：它留在历史里，
     * 图被摘掉之后仍要读得通。⚠️ **没附上的必须说出来**（静默的表现是"模型像没看见那个文件"）。
     * 全空时回空串：没附件的消息一个字都不能多。
     *
     * @param files    附上的文件与目录：路径 → 是不是目录（保持顺序请传 LinkedHashMap）
     * @param images   附上的图的显示名
     * @param fails    没附上的
     * @param overflow 超过单次上限、根本没读的：{@code [个数, 上限]}，或 null
     */
    public static String attachedLine(Map<String, Boolean> files, List<String> images, List<AttachFail> fails, int[] overflow) {
        files = files == null ? Map.of() : files;
        images = images == null ? List.of() : images;
        fails = fails == null ? List.of() : fails;
        if (files.isEmpty() && fails.isEmpty() && overflow == null) {
            if (images.isEmpty()) return "";
            return (images.size() == 1 ? "\n\n⚠️ 这条消息附了一张图：" : "\n\n⚠️ 这条消息附了 " + images.size() + " 张图：")
                    + "\n" + numbered(images);
        }
        StringBuilder sb = new StringBuilder("\n\n⚠️ ");
        if (files.isEmpty() && images.isEmpty()) {
            sb.append("这条消息的 @ 提及没有附上任何东西：\n");
        } else {
            sb.append("这条消息附了").append(summary(files.size(), images.size())).append("：\n");
            // 编号名单：文件在前、图在后 —— 与消息里块的顺序一致；目录 / 图各自标出来
            java.util.ArrayList<String> entries = new java.util.ArrayList<>();
            files.forEach((p, dir) -> entries.add(Boolean.TRUE.equals(dir) ? p + "（目录）" : p));
            for (String n : images) entries.add(n + "（图）");
            sb.append(numbered(entries));
        }
        for (AttachFail f : fails) {
            sb.append("没附上：").append(f.path()).append("（").append(f.reason() != null ? f.reason() : "说不上为什么").append("）\n");
        }
        if (overflow != null) {
            sb.append("（还有 ").append(overflow[0]).append(" 个 @ 提及没有附：一次最多附 ").append(overflow[1]).append(" 个）\n");
        }
        return sb.toString();
    }

    private static String summary(int nf, int ni) {
        if (nf > 0 && ni > 0) return nf + " 个文件、" + ni + " 张图";
        if (nf > 0) return nf == 1 ? "一个文件" : nf + " 个文件";
        return ni == 1 ? "一张图" : ni + " 张图";
    }

    private static String numbered(List<String> names) {
        StringBuilder sb = new StringBuilder();
        int i = 1;
        for (String n : names) sb.append("  ").append(i++).append(". ").append(n).append("\n");
        return sb.toString();
    }

